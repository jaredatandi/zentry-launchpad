import { Pool, type QueryResultRow } from "pg";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { seedDemo } from "./seed";
import type { AsyncDatabase, AsyncStatement } from "./types";

/** Postgres version of the SQLite schema. Kept as a mechanical translation so
 *  every feature (CHECKs, FKs, indexes, demo seed) stays identical. */
function toPostgresSchema(sql: string): string {
  return sql
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace(/NUMERIC/g, "DOUBLE PRECISION");
}

/** Rewrite SQLite's `?` placeholders to Postgres `$1..$n` without touching
 *  quoted literal text. The app's SQL only uses `?` as a bind marker. */
function toPostgresParams(sql: string): string {
  let out = "";
  let quote = "";
  let index = 0;
  for (let i = 0; i < sql.length; i += 1) {
    const ch = sql[i]!;
    if (quote) {
      out += ch;
      if (ch === quote && sql[i - 1] !== "\\") quote = "";
      continue;
    }
    if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
      continue;
    }
    if (ch === "?") {
      index += 1;
      out += `$${index}`;
      continue;
    }
    out += ch;
  }
  return out;
}

/** pg returns COUNT() as a string and NUMERIC as a string; the schema uses
 *  DOUBLE PRECISION for money, so only aggregate aliases need coercion. */
function normaliseRow(row: QueryResultRow | undefined): any {
  if (!row) return undefined;
  const out: Record<string, unknown> = { ...row };
  for (const key of ["n", "total", "converted"]) {
    if (key in out && out[key] !== null && out[key] !== undefined) {
      out[key] = Number(out[key]);
    }
  }
  return out;
}

function statement(pool: Pool, originalSql: string): AsyncStatement {
  const isInsert = /^\s*INSERT\b/i.test(originalSql);
  const returning = isInsert && !/\bRETURNING\b/i.test(originalSql) ? " RETURNING id" : "";
  const sql = toPostgresParams(originalSql) + returning;

  return {
    async get(...params: unknown[]) {
      const result = await pool.query(sql, params as unknown[]);
      return normaliseRow(result.rows[0]);
    },
    async all(...params: unknown[]) {
      const result = await pool.query(sql, params as unknown[]);
      return result.rows.map((row) => normaliseRow(row));
    },
    async run(...params: unknown[]) {
      const result = await pool.query(sql, params as unknown[]);
      const id = isInsert ? Number((result.rows[0] as { id?: unknown } | undefined)?.id ?? 0) : 0;
      return { lastInsertRowid: id || Number(result.rows[0]?.lastInsertRowid ?? 0), changes: result.rowCount ?? 0 };
    },
  };
}

function migrationSql(): string {
  const candidates = [
    join(__dirname, "..", "..", "migrations", "001_initial.sql"),
    join(__dirname, "migrations", "001_initial.sql"),
  ];
  const found = candidates.find(existsSync);
  if (!found) throw new Error("Migration file 001_initial.sql not found");
  return readFileSync(found, "utf8");
}

async function syncSequences(pool: Pool): Promise<void> {
  for (const table of ["leads", "clients", "pages", "enquiries", "invoices", "activity"]) {
    await pool.query(
      `SELECT setval(pg_get_serial_sequence($1, 'id'), COALESCE((SELECT MAX(id) FROM ${table}), 1))`,
      [table],
    );
  }
}

export function openPostgresDatabase(connectionString: string, withSeed = true): AsyncDatabase {
  const pool = new Pool({
    connectionString,
    ssl: { rejectUnauthorized: false },
    max: 3,
    connectionTimeoutMillis: 10_000,
  });

  const ready = (async () => {
    await pool.query(toPostgresSchema(migrationSql()));
    if (withSeed) {
      const db: AsyncDatabase = {
        prepare: (sql) => statement(pool, sql),
        exec: async (sql) => {
          await pool.query(toPostgresSchema(sql));
        },
        ready: Promise.resolve(),
        close: () => pool.end(),
      };
      await seedDemo(db);
      await syncSequences(pool);
    }
  })();

  return {
    prepare: (sql) => statement(pool, sql),
    exec: async (sql) => {
      await pool.query(toPostgresSchema(sql));
    },
    ready,
    close: () => pool.end(),
  };
}
